#!/usr/bin/env python3
"""
predict_nowcast.py — loads the trained ConvLSTM rainfall-nowcast model and
runs ONE prediction. Deliberately simple and stateless: the Node.js backend
calls this fresh for each request rather than keeping a Python process
running, since predictions are only needed occasionally (not per-second).

Input (via stdin):  a JSON array of 6 past hourly rainfall grids, each 15x15
                     numbers in millimeters — shape (6, 15, 15).
Output (to stdout): a JSON array of 3 predicted future hourly rainfall
                     grids, same 15x15 shape — shape (3, 15, 15).
"""
import sys
import json
import numpy as np
import tensorflow as tf

MODEL_DIR = 'models/nowcast_savedmodel'


def main():
    input_mm = np.array(json.loads(sys.stdin.read()), dtype=np.float32)
    if input_mm.shape != (6, 15, 15):
        print(json.dumps({'error': f'expected input shape (6,15,15), got {list(input_mm.shape)}'}))
        sys.exit(1)

    model = tf.saved_model.load(MODEL_DIR)
    infer = model.signatures['serving_default']

    # Same log1p transform used during training (rainfall data is mostly
    # zeros with occasional big spikes — this keeps training/inference
    # numerically stable). Inverted back to real mm before returning.
    x_log = np.log1p(input_mm)[np.newaxis, ..., np.newaxis]  # (1, 6, 15, 15, 1)
    x_tensor = tf.constant(x_log, dtype=tf.float32)

    # Read the actual input/output tensor names from the model itself
    # rather than hardcoding a guess — SavedModel signature names are
    # generated by Keras and shouldn't be assumed.
    input_key = list(infer.structured_input_signature[1].keys())[0]
    result = infer(**{input_key: x_tensor})
    output_key = list(result.keys())[0]
    pred_log = result[output_key].numpy()[0]  # (15, 15, 3)

    pred_mm = np.maximum(np.expm1(pred_log), 0)   # rainfall can't be negative
    pred_mm_frames = np.transpose(pred_mm, (2, 0, 1))  # -> (3, 15, 15)

    print(json.dumps(pred_mm_frames.tolist()))


if __name__ == '__main__':
    main()
